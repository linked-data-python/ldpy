class Row(tuple):
    """A solution of an m{ ... } of arity >= 2: an unpackable tuple, named
    access (row.s) and access by variable (row[?v] or row['v'])."""

    def __new__(cls, values, fields):
        r = tuple.__new__(cls, values)
        r._fields = fields
        return r

    def __getattr__(self, name):
        try:
            return self[self._fields.index(name)]
        except ValueError:
            raise AttributeError(name)

    def __getitem__(self, key):
        if isinstance(key, (str, Variable)):
            return tuple.__getitem__(self, self._fields.index(str(key)))
        return tuple.__getitem__(self, key)

    def __repr__(self):
        return "Row(%s)" % ", ".join(
            "%s=%r" % (f, tuple.__getitem__(self, i))
            for i, f in enumerate(self._fields))


class _RowSeq:
    """The same Row for MicroPython, which cannot subclass tuple with
__new__: a small sequence that unpacks, compares to a tuple, and
answers to names and variables."""

    __slots__ = ("_values", "_fields")

    def __init__(self, values, fields):
        self._values = tuple(values)
        self._fields = fields

    def __iter__(self):
        return iter(self._values)

    def __len__(self):
        return len(self._values)

    def __eq__(self, other):
        return self._values == (other._values if isinstance(other, _RowSeq)
                                else other)

    def __hash__(self):
        return hash(self._values)

    def __getattr__(self, name):
        try:
            return self._values[self._fields.index(name)]
        except ValueError:
            raise AttributeError(name)

    def __getitem__(self, key):
        if isinstance(key, (str, Variable)):
            return self._values[self._fields.index(str(key))]
        return self._values[key]

    def __repr__(self):
        return "Row(%s)" % ", ".join(
            "%s=%r" % (f, v) for f, v in zip(self._fields, self._values))


#: The row class of this Python: tuple-based, unless tuple cannot be
#: subclassed with __new__ (MicroPython).
_ROW = Row if hasattr(tuple, "__new__") else _RowSeq


def _match_prepare(patterns, bindings):
    """Patterns ready for matching: bn -> an anonymous variable shared by
    index, slot -> a value, variables bound by the bindings -> a term."""
    init = {}
    if bindings:
        for k, v in bindings.items():
            init[Variable(str(k))] = node(v)
    out = []
    slots = {}
    for s, p, o in patterns:
        tr = []
        for t in (s, p, o):
            tt = type(t)
            if tt is bn:
                t = Variable("__bn%d" % t.index)
            elif tt is slot:
                if t.bound:
                    slots[t.index] = node(t.value)
                t = slots[t.index]
            if isinstance(t, Variable) and t in init:
                t = init[t]
            tr.append(t)
        out.append(tuple(tr))
    return out, init


class Match:
    """The value of an m{ ... } island (record ldpy/016): a nested-loop join
    over graph.triples(), in the order written — no engine, no heuristic.
    Lazy: iterating, testing or first() only matches as much as is needed.
    """

    __slots__ = ("graph", "patterns", "project", "bindings")

    def __init__(self, graph, patterns, project, bindings=None):
        self.graph = graph
        self.patterns = patterns
        self.project = project
        self.bindings = bindings

    def __call__(self, graph=None, bindings=None):
        return Match(self.graph if graph is None else graph,
                     self.patterns, self.project,
                     self.bindings if bindings is None else bindings)

    def solutions(self):
        """Generator of solution mappings (Bindings variable -> term),
        initial bindings included (projected, record ldpy/019)."""
        if self.graph is None:
            raise RuntimeError(
                "m{ } with no graph: declare '@graph ...' in scope, or "
                "apply the pattern to a graph — m{ ... }(g)")
        patterns, init = _match_prepare(self.patterns, self.bindings)
        graph = self.graph

        def join(i, sm):
            if i == len(patterns):
                yield sm
                return
            pat = []
            var_pos = []
            for k, t in enumerate(patterns[i]):
                if isinstance(t, Variable):
                    v = sm.get(t)
                    if v is None:
                        var_pos.append((k, t))
                        v = None
                    pat.append(v)
                else:
                    pat.append(t)
            for found in graph.triples(tuple(pat)):
                sm2 = dict(sm)
                ok = True
                for k, var in var_pos:
                    val = found[k]
                    prev = sm2.get(var)
                    if prev is not None and prev != val:
                        ok = False
                        break
                    sm2[var] = val
                if ok:
                    yield from join(i + 1, sm2)

        yield from join(0, dict(init))

    def __iter__(self):
        proj = self.project
        if len(proj) == 1:
            v = Variable(proj[0])
            for sm in self.solutions():
                yield sm.get(v)
        else:
            vs = [Variable(x) for x in proj]
            for sm in self.solutions():
                yield _ROW((sm.get(x) for x in vs), list(proj))

    def __bool__(self):
        for _ in self.solutions():
            return True
        return False

    def first(self):
        """The first solution, or None if there is none (~ g.value)."""
        for x in self:
            return x
        return None

    def one(self):
        """The single solution; raises if there are zero or several."""
        it = iter(self)
        try:
            first = next(it)
        except StopIteration:
            raise ValueError("m{ }.one() : aucune solution")
        for _ in it:
            raise ValueError("m{ }.one() : plusieurs solutions")
        return first

    def count(self):
        """Number of solutions — consumes the matching (len() fails)."""
        n = 0
        for _ in self.solutions():
            n += 1
        return n

    def __repr__(self):
        return "m{ %d motif(s), projection %r }" % (
            len(self.patterns), tuple(self.project))


def match(graph, patterns, project, bindings=None):
    """Build the value of an m{ ... } island (record ldpy/016)."""
    return Match(graph, patterns, project, bindings)


