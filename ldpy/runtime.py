_URI_CACHE = {}


def URIRef(value, base=None):
    """The backend's URIRef with a cache (key = the string). The IRIs emitted
    by the transpiler are CONSTANTS of the program: without a cache, every
    turn of a loop over a g{...} rebuilt them (see OPTIMIZATION.md). The
    cache is bounded by the text of the programs; a 1M-entry guard covers
    dynamic uses through the API."""
    if base is not None:
        return _URIRef(value, base)
    u = _URI_CACHE.get(value)
    if u is None:
        if len(_URI_CACHE) > 1000000:
            return _URIRef(value)
        u = _URI_CACHE.setdefault(value, _URIRef(value))
    return u

