"""Runtime Linked-Data Python v2.

The code generated by the transpiler imports this module under the reserved
alias `_ldpy_` and uses ONLY this facade — never an RDF library directly.
The library underneath is chosen by `ldpy.backend`: rdflib on the host,
urdflib on a MicroPython device. The generated code is the same on both.

Emission and runtime choices are explained in docs/explanation/.
"""

